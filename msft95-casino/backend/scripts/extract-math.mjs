// Copies the slots + keno game math out of the MSFT95 site (index.html) into src/games/math.js,
// so the server settles bets with exactly the code the website animates.
//   node scripts/extract-math.mjs path/to/index.html
import fs from "node:fs";
import crypto from "node:crypto";

const src = fs.readFileSync(process.argv[2], "utf8");
function cut(from, to) {
  const a = src.indexOf(from); if (a < 0) throw new Error("not found: " + from);
  const b = src.indexOf(to, a); if (b < 0) throw new Error("not found: " + to);
  return src.slice(a, b);
}
const slots = cut("var SLOTS_MATH={", "// unbiased 0..1 from the browser");
const keno = cut("var KENO_MATH={", "/* ================= Kimmy Keno — the app");
const body = slots + "\n" + keno;
const hash = crypto.createHash("sha256").update(body).digest("hex");
const out = `// GENERATED by scripts/extract-math.mjs from the MSFT95 site — do not edit by hand.
// source sha256: ${hash}
/* eslint-disable */
${body}
export const MATH_SOURCE_SHA256 = ${JSON.stringify(hash)};
export { SLOTS_MATH, slotsGrid, slotsEvaluate, slotsRandomStops, KENO_MATH, kenoDraw, kenoEvaluate };
`;
fs.writeFileSync(new URL("../src/games/math.js", import.meta.url), out);
console.log("wrote src/games/math.js", hash);
